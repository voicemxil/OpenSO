        public PixelFont(GraphicsDevice gd)
        {
            int count = LastChar - FirstChar + 1;
            var data = new Color[count * Advance * GlyphH];
            int atlasW = count * Advance;
            for (int c = 0; c < count; c++)
            {
                if (!Glyphs.TryGetValue((char)(FirstChar + c), out var rows)) continue;
                for (int y = 0; y < GlyphH; y++)
                    for (int x = 0; x < GlyphW; x++)
                        if (rows[y][x] == '#') data[y * atlasW + c * Advance + x] = Color.White;
            }
            Atlas = new Texture2D(gd, atlasW, GlyphH);
            Atlas.SetData(data);
        }

        public void Draw(SpriteBatch sb, string text, Vector2 pos, Color color, float scale = 2f)
        {
            float x = pos.X;
            foreach (var raw in text)
            {
                var ch = char.ToUpperInvariant(raw);
                if (ch >= FirstChar && ch <= LastChar)
                {
                    var src = new Rectangle((ch - FirstChar) * Advance, 0, GlyphW, GlyphH);
                    sb.Draw(Atlas, new Vector2(x, pos.Y), src, color, 0f, Vector2.Zero, scale, SpriteEffects.None, 0f);
                }
                x += Advance * scale;
            }
        }

        public float Measure(string text, float scale = 2f) => text.Length * Advance * scale;
    }
